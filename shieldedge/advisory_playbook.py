"""
Vetted remediation playbook and template explanations for ShieldEdge.

Remediation steps are *never* generated by the LLM: they come from this fixed,
reviewed list so the assistant cannot recommend unsafe actions (e.g. "open the
link to check it"). Llama only writes the plain-language explanation; when
Llama is unavailable or its output fails validation, `template_explanation`
is used instead.

Reporting channels (India):
  * 1930 / cybercrime.gov.in  - National Cyber Crime Helpline (MHA, I4C):
                                financial fraud, report immediately.
  * Sanchar Saathi "Chakshu"  - sancharsaathi.gov.in: report suspected fraud
                                calls / SMS / WhatsApp messages.
  * 1909                      - TRAI DND: complain about unsolicited commercial SMS.
  * incident@cert-in.org.in   - CERT-In: cyber security incidents.
"""

REMEDIATION = {
    "URL": [
        "Do not open, forward or enter any details on this link.",
        "If you already entered a password, OTP or card number there, change the password from the official app and call your bank using the number on your card.",
        "Report the link at cybercrime.gov.in; if money was lost, call 1930 immediately.",
    ],
    "SMS": [
        "Do not click links, call numbers or reply to this message.",
        "Never share an OTP, UPI PIN, CVV or Aadhaar/PAN details - banks and government offices never ask for them by SMS.",
        "Report the sender on Sanchar Saathi (Chakshu) at sancharsaathi.gov.in; if money was lost, call 1930.",
    ],
    "NETWORK_FLOW": [
        "Disconnect the affected device from Wi-Fi/Ethernet until it has been checked.",
        "Run a full malware scan on that device and change its account passwords from a different, clean device.",
        "Change the router admin and Wi-Fi passwords and disable unknown port forwards/UPnP; report serious incidents to incident@cert-in.org.in.",
    ],
}

SUSPICIOUS_STEP = "If unsure, verify through the organisation's official app or website that you open yourself - not through this message or link."


def remediation_steps(input_type: str, verdict: str) -> list:
    steps = list(REMEDIATION.get(input_type, REMEDIATION["URL"]))
    if verdict == "SUSPICIOUS":
        steps.insert(0, SUSPICIOUS_STEP)
    return steps


def template_explanation(evidence: dict) -> str:
    """Deterministic explanation built only from the detector signals."""
    verdict = evidence.get("verdict", "SUSPICIOUS")
    itype = evidence.get("input_type")
    conf = float(evidence.get("confidence", 0.0))
    signals = evidence.get("signals", [])
    reasons = "; ".join(s.rstrip(".") for s in signals[:4]) if signals else "its overall pattern looked unusual to the model"

    if itype == "URL":
        what = "This link"
        why = "Fake links like this are used to steal banking passwords, OTPs and card details."
    elif itype == "SMS":
        what = "This SMS"
        why = "Scam messages create urgency or promise rewards so that people act before thinking."
    else:
        what = "This network connection"
        why = "Traffic like this can mean malware, a compromised device or someone scanning your network."

    certainty = "looks like" if verdict == "SUSPICIOUS" else "was flagged as"
    return f"{what} {certainty} {verdict.lower()} ({conf:.0%} confidence) because: {reasons}. {why}"


def format_advisory(explanation: str, steps: list, caveat: str = "") -> str:
    body = "\n".join(f"{i}. {s}" for i, s in enumerate(steps, 1))
    text = f"[EXPLANATION]\n{explanation}\n\n[WHAT TO DO]\n{body}"
    if caveat:
        text += f"\n\nNote: {caveat}"
    return text
